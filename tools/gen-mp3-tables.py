#!/usr/bin/env python3
"""Generates src/OneAudio/Mp3/Mp3Tables.g.cs from the text of a public Layer III document:

  M. Sieler, R. Sperschneider, "MPEG-Layer3 Bitstream Syntax and Decoding", Fraunhofer IIS, issue 1.2, 1997
  (its Tables 23-60: pretab, Huffman code tables, scalefactor bands, alias-reduction coefficients, and the
  synthesis window D[i] of the polyphase filterbank).

Usage: tools/gen-mp3-tables.py <pdftotext -layout output of that document> > src/OneAudio/Mp3/Mp3Tables.g.cs
The numbers are facts of the format; the generator only transcribes them and checks their shape.
"""
import re
import sys

text = open(sys.argv[1], encoding="utf-8", errors="replace").read().splitlines()

# Split into "Table N" sections (a heading line is exactly "Table N").
sections = {}
cur = None
for line in text:
    m = re.match(r"^\s*Table (\d+)\s*$", line)
    if m:
        cur = int(m.group(1))
        sections[cur] = []
        continue
    if cur is not None:
        sections[cur].append(line)

# Huffman tables: table number in the document -> (table id, dimension).
huff_docs = {24: ("A", 4), 25: ("B", 4), 27: (1, 2), 28: (2, 3), 29: (3, 3), 30: (5, 4), 31: (6, 4), 32: (7, 6),
             33: (8, 6), 34: (9, 6), 35: (10, 8), 36: (11, 8), 37: (12, 8), 38: (13, 16), 39: (15, 16),
             40: (16, 16), 41: (24, 16)}
row2 = re.compile(r"^\s*(\d+)\s+(\d+)\s+(\d+)\s+([01]+)\s*$")
# Some pages of the source lose the gap between y and hlen ("7  010  0001001000" is y=0, hlen=10). The code
# length always equals hlen, so the glued digits are y followed by len(hcod).
row_glued = re.compile(r"^\s*(\d+)\s+(\d+)\s+([01]+)\s*$")
row4 = re.compile(r"^\s*([01])\s+([01])\s+([01])\s+([01])\s+(\d+)\s+([01]+)\s*$")

out = []
w = out.append
w("// <auto-generated>")
w("// Produced by tools/gen-mp3-tables.py from the public Layer III tables of M. Sieler and R. Sperschneider,")
w("// \"MPEG-Layer3 Bitstream Syntax and Decoding\" (Fraunhofer IIS, 1997). Do not edit by hand.")
w("// </auto-generated>")
w("namespace OneAudio.Mp3;")
w("")
w("internal static class Mp3Tables")
w("{")
w("    // Each Huffman entry is (code length << 20) | code, indexed x * dimension + y (count1 tables: v, w, x, y bits).")
for doc, (tid, dim) in huff_docs.items():
    entries = {}
    for line in sections[doc]:
        if tid in ("A", "B"):
            m = row4.match(line)
            if m:
                v, ww, x, y, hl, hc = m.groups()
                idx = int(v) * 8 + int(ww) * 4 + int(x) * 2 + int(y)
                entries[idx] = (int(hl), hc)
        else:
            m = row2.match(line)
            g = row_glued.match(line)
            if g and not m:
                gx, glue, gc = g.groups()
                if not glue.endswith(str(len(gc))) or len(glue) == len(str(len(gc))):
                    sys.exit(f"cannot split glued row in table {doc}: {line}")
                m = (gx, glue[: -len(str(len(gc)))], str(len(gc)), gc)
            if m:
                x, y, hl, hc = m if isinstance(m, tuple) else m.groups()
                x, y, hl = int(x), int(y), int(hl)
                if x >= dim or y >= dim or len(hc) != hl:
                    sys.exit(f"bad row in table {doc}: {line}")
                entries[x * dim + y] = (hl, hc)
    n = 16 if tid in ("A", "B") else dim * dim
    if len(entries) != n:
        sys.exit(f"table {doc} ({tid}) has {len(entries)} entries, expected {n}")
    vals = []
    for i in range(n):
        hl, hc = entries[i]
        if len(hc) != hl:
            sys.exit(f"table {doc}: length mismatch at {i}")
        vals.append(f"0x{(hl << 20) | int(hc, 2):X}")
    name = f"Huff{tid}"
    w(f"    public static readonly uint[] {name} = [{', '.join(vals)}];")
w("")

# Scalefactor bands.
rates = [(42, 43, "8000"), (44, 45, "11025"), (46, 47, "12000"), (48, 49, "16000"), (50, 51, "22050"),
         (52, 53, "24000"), (54, 55, "32000"), (56, 57, "44100"), (58, 59, "48000")]
rowb = re.compile(r"^\s*(\d+)\s+(\d+)\s+(\d+)\s+(\d+)\s*$")


def starts(doc, total):
    s = []
    for line in sections[doc]:
        m = rowb.match(line)
        if m:
            band, width, a, b = map(int, m.groups())
            if band != len(s) or b - a + 1 != width or (s and a != s[-1][0] + s[-1][1]):
                sys.exit(f"table {doc}: inconsistent band row {line}")
            s.append((a, width))
    r = [a for a, _ in s]
    end = s[-1][0] + s[-1][1]
    if end > total:
        sys.exit(f"table {doc}: bands run past {total}")
    # The tables list the bands that carry scalefactors; the rest of the spectrum is one more band without them.
    if end < total:
        r.append(end)
    r.append(total)
    return r


w("    /// <summary>Long-block band start lines per sample rate (8, 11.025, 12, 16, 22.05, 24, 32, 44.1, 48 kHz); the last entry is 576.</summary>")
w("    public static readonly int[][] LongBands = [")
for lo, sh, rate in rates:
    w(f"        [{', '.join(map(str, starts(lo, 576)))}],  // {rate} Hz")
w("    ];")
w("    /// <summary>Short-block band start lines (per window) in the same rate order; the last entry is 192.</summary>")
w("    public static readonly int[][] ShortBands = [")
for lo, sh, rate in rates:
    w(f"        [{', '.join(map(str, starts(sh, 192)))}],  // {rate} Hz")
w("    ];")
w("")

# Alias reduction coefficients c[i].
alias = []
for line in sections[60]:
    m = re.match(r"^\s*(\d+)\s+(-?[0-9.]+)\s*$", line)
    if m:
        alias.append(m.group(2))
if len(alias) != 8:
    sys.exit("alias table incomplete")
w(f"    public static readonly double[] AliasC = [{', '.join(alias)}];")
w("")

# Synthesis window: D[i] are multiples of 2^-16, stored as integers.
d = {}
for line in text:
    for m in re.finditer(r"D\[\s*(\d+)\]\s*=\s*(-?\d+),(\d+)", line):
        d[int(m.group(1))] = float(m.group(2) + "." + m.group(3))
if sorted(d) != list(range(512)):
    sys.exit("synthesis window incomplete")
nums = []
for i in range(512):
    n = round(d[i] * 65536)
    if abs(n / 65536 - d[i]) > 1e-8:
        sys.exit(f"D[{i}] is not a multiple of 2^-16")
    nums.append(str(n))
w("    /// <summary>The synthesis window D[i] times 65536 (every coefficient is a multiple of 2^-16).</summary>")
w(f"    public static readonly int[] SynthesisWindow65536 = [{', '.join(nums)}];")
w("}")
print("\n".join(out))
