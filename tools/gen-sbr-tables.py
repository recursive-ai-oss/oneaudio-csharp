#!/usr/bin/env python3
"""Generates src/OneAudio/Aac/AacSbrTables.g.cs: the constant tables of spectral band replication and parametric
stereo (the SBR Huffman trees, the noise-substitution phase table, the 640-tap QMF prototype filter, the parametric
stereo group maps, fractional-delay phase factors, quantiser levels and hybrid filter coefficients).

The data comes from the constant tables of the 3GPP TS 26.410 floating-point decoder (file sbr_rom.c of the SBR
decoder part), which the 3GPP specifications treat as the normative numeric data of ISO/IEC 14496-3 4.6.18 and
Annex 4.A/4.B tables. Nothing else is read from that file.

Usage: tools/gen-sbr-tables.py <path to sbr_rom.c> > src/OneAudio/Aac/AacSbrTables.g.cs
"""
