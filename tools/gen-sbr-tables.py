    ("RandomPhase", "sbr_randomPhase", "float"),
    ("QmfWindow", "sbr_qmf_64_640", "float"),
    ("PsGroupBorders", "groupBorders", "sbyte"),
    ("PsBins2Group", "bins2groupMap", "short"),
    ("PsFractDelayReQmf", "aFractDelayPhaseFactorReQmf", "float"),
    ("PsFractDelayImQmf", "aFractDelayPhaseFactorImQmf", "float"),
    ("PsFractDelayReSubQmf", "aFractDelayPhaseFactorReSubQmf", "float"),
    ("PsFractDelayImSubQmf", "aFractDelayPhaseFactorImSubQmf", "float"),
    ("PsSerReQmf0", "aFractDelayPhaseFactorSerReQmf0", "float"),
    ("PsSerReQmf1", "aFractDelayPhaseFactorSerReQmf1", "float"),
    ("PsSerReQmf2", "aFractDelayPhaseFactorSerReQmf2", "float"),
    ("PsSerImQmf0", "aFractDelayPhaseFactorSerImQmf0", "float"),
    ("PsSerImQmf1", "aFractDelayPhaseFactorSerImQmf1", "float"),
    ("PsSerImQmf2", "aFractDelayPhaseFactorSerImQmf2", "float"),
    ("PsSerReSubQmf0", "aFractDelayPhaseFactorSerReSubQmf0", "float"),
    ("PsSerReSubQmf1", "aFractDelayPhaseFactorSerReSubQmf1", "float"),
    ("PsSerReSubQmf2", "aFractDelayPhaseFactorSerReSubQmf2", "float"),
    ("PsSerImSubQmf0", "aFractDelayPhaseFactorSerImSubQmf0", "float"),
    ("PsSerImSubQmf1", "aFractDelayPhaseFactorSerImSubQmf1", "float"),
    ("PsSerImSubQmf2", "aFractDelayPhaseFactorSerImSubQmf2", "float"),
    ("PsScaleFactors", "scaleFactors", "float"),
    ("PsScaleFactorsFine", "scaleFactorsFine", "float"),
    ("PsAlphas", "alphas", "float"),
    ("PsHybrid6", "p2_6", "float"),
    ("PsHybrid13", "p8_13", "float"),
    ("StartFreq16", "sbr_start_freq_16", "byte"),
    ("StartFreq22", "sbr_start_freq_22", "byte"),
    ("StartFreq24", "sbr_start_freq_24", "byte"),
