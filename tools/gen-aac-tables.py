#!/usr/bin/env python3
"""Generates src/OneAudio/Aac/AacTables.g.cs: the AAC spectral and scalefactor Huffman codebooks and the
scalefactor-band offset tables.

The data comes from the constant tables of the 3GPP TS 26.410 floating-point decoder (file aac_rom.c of the
decoder part), which store each codebook as a two-bits-per-step decoding tree. This script walks those trees and
writes (code length, code, value) triples, so the C# decoder builds its own lookup tables and shares no structure
with the source. Nothing else is read from that file.

Usage: tools/gen-aac-tables.py <path to aac_rom.c> > src/OneAudio/Aac/AacTables.g.cs
"""
import re
import sys


def parse_arrays(text):
    arrays = {}
    for m in re.finditer(r"(?:static\s+)?const\s+(?:unsigned\s+short|short)\s+(\w+)\s*(\[[^\]]*\])+\s*=\s*\{(.*?)\n\};", text, re.S):
        name = m.group(1)
        nums = [int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|-?\d+", re.sub(r"/\*.*?\*/", "", m.group(3), flags=re.S))]
        arrays[name] = nums
    return arrays


def walk(rows):
    """Returns sorted (length, code, value) for a tree stored as rows of four 16-bit entries."""
    out = {}
    stack = [(0, 0, 0)]  # row, bits so far, steps taken
    while stack:
        row, bits, depth = stack.pop()
        for chunk in range(4):
            v = rows[row][chunk]
            nbits = (bits << 2) | chunk
            if v & 1:
                push_back = (v >> 1) & 1
                length = 2 * (depth + 1) - push_back
                code = nbits >> push_back
                out[(length, code)] = v >> 2
            else:
                stack.append((v >> 2, nbits, depth + 1))
    return sorted((l, c, v) for (l, c), v in out.items())


def main():
    text = open(sys.argv[1]).read()
    arrays = parse_arrays(text)
    books = {}
    for name, nums in arrays.items():
        m = re.fullmatch(r"HuffmanCodeBook_(\d+|SCL)", name)
        if m:
            idx = 12 if m.group(1) == "SCL" else int(m.group(1))
            rows = [nums[i:i + 4] for i in range(0, len(nums), 4)]
            books[idx] = walk(rows)
    print("// <auto-generated> by tools/gen-aac-tables.py from the AAC Huffman and scalefactor-band constants of the 3GPP TS 26.410 decoder.")
    print("// Codebook values are packed as the source packs them: for the 4-tuple books the first coefficient is in the low bits,")
    print("// each field is (value + offset) in 2 bits (books 1-4), 4 bits (books 5-10) or 5 bits (book 11). Book 12 is the scalefactor book")
    print("// (value = delta + 60). </auto-generated>")
    print("namespace OneAudio.Aac;")
    print()
    print("internal static class AacTables")
    print("{")
    for idx in sorted(books):
        b = books[idx]
        print(f"    /// <summary>Codebook {idx}: code lengths, codes and packed values, sorted by length then code.</summary>")
        print(f"    internal static ReadOnlySpan<byte> Lengths{idx} => [{', '.join(str(l) for l, _, _ in b)}];")
        print(f"    internal static ReadOnlySpan<uint> Codes{idx} => [{', '.join(str(c) for _, c, _ in b)}];")
        print(f"    internal static ReadOnlySpan<ushort> Values{idx} => [{', '.join(str(v) for _, _, v in b)}];")
        print()
    names = {
        "sfb_48_1024": "Long48", "sfb_48_128": "Short48", "sfb_32_1024": "Long32", "sfb_24_1024": "Long24",
        "sfb_24_128": "Short24", "sfb_16_1024": "Long16", "sfb_16_128": "Short16", "sfb_8_1024": "Long8", "sfb_8_128": "Short8",
    }
    for src, dst in names.items():
        print(f"    /// <summary>Scalefactor band offsets ({src}).</summary>")
        print(f"    internal static ReadOnlySpan<short> Sfb{dst} => [{', '.join(str(x) for x in arrays[src])}];")
        print()
    print("}")


main()
